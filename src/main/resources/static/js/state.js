export const mathEvaluators = {
  SQR: (x) => x * x,
  IDENTITY: (x) => x,
  LINEAR: (x) => x,
  CONSTANT: (_, c = 0) => c,
  CONST: (_, c = 0) => c,
  UNIT: () => 1,
  ZERO: () => 0,
  COS: (x) => Math.cos(x),
  SIN: (x) => Math.sin(x),
  TAN: (x) => Math.tan(x),
  CTG: (x) => 1 / Math.tan(x),
  CUBE: (x) => x * x * x,
  SQRT: (x) => Math.sqrt(x),
  CBRT: (x) => Math.cbrt(x),
  RECIP: (x) => 1 / x,
  ABS: (x) => Math.abs(x),
  EXP: (x) => Math.exp(x),
  LOG: (x) => Math.log(x),
  LN: (x) => Math.log(x),
  LOG10: (x) => Math.log10(x),
  LOGA: (x, a = 10) => Math.log(x) / Math.log(a || 10),
};

